"""Circle barrier envelopes and cooperative arcs, without desktop plotting."""

from math import acos, atan2, ceil, cos, pi, sin, sqrt
import time
from typing import Any
import numpy as np

import geometry_common as solve_p_module
from geometry_common import boundary_derivative, lifted_distance

TAU = 2.0 * pi
MODE_LABELS = {("-", "+"): "p1", ("+", "-"): "p2", ("-", "-"): "p3", ("+", "+"): "p4"}


def _as_point(x: Any, name: str) -> np.ndarray:
    point = np.asarray(x, dtype=float)
    if point.shape != (2,) or not np.all(np.isfinite(point)):
        raise ValueError(f"{name} must be a finite two-dimensional point.")
    return point


def _rotation(angle: float) -> np.ndarray:
    c, s = cos(angle), sin(angle)
    return np.array([[c, -s], [s, c]], dtype=float)


def _canonical_one_defender_barrier(
    defender_radius: float,
    radius: float,
    alpha: float,
    resolution: int,
) -> np.ndarray:
    """Return the canonical 1D1A barrier as an explicit circle envelope."""

    rho = defender_radius / radius
    if rho < 1.0 - 1e-12:
        raise ValueError("A defender cannot lie inside the target disk.")
    n_half = max(80, int(resolution) // 2)

    defender_tangent = sqrt(
        max(0.0, defender_radius * defender_radius - radius * radius)
    )
    tangent_angle = acos(np.clip(radius / defender_radius, -1.0, 1.0))
    direct_exists = alpha < 1.0
    phi_start = 0.5 * pi if direct_exists else 0.5 * pi + tangent_angle
    d_max = solve_p_module.compute_d_max(
        np.array([0.0, defender_radius]), alpha, radius
    )
    phi_end = 0.5 * pi + tangent_angle + (d_max - defender_tangent) / radius

    def envelope(target_angles: np.ndarray) -> np.ndarray:
        phi = np.asarray(target_angles, dtype=float)
        distances = lifted_distance((defender_radius, 0.5 * pi), radius, phi, radius)
        derivatives = boundary_derivative(
            (defender_radius, 0.5 * pi, tangent_angle, defender_tangent),
            phi,
            -1,
            radius,
        )

        radial = np.column_stack((np.cos(phi), np.sin(phi)))
        tangent = np.column_stack((-np.sin(phi), np.cos(phi)))
        eta = np.clip(alpha * derivatives / radius, -1.0, 1.0)
        outward = (
            np.sqrt(np.maximum(0.0, 1.0 - eta * eta))[:, None] * radial
            - eta[:, None] * tangent
        )
        return radius * radial + alpha * distances[:, None] * outward

    dense_count = max(4 * n_half + 1, 321)
    dense_phi = np.linspace(phi_start, phi_end, dense_count)
    dense_points = envelope(dense_phi)
    dense_theta = np.unwrap(np.arctan2(dense_points[:, 1], dense_points[:, 0]))
    increasing = np.r_[True, np.diff(dense_theta) > 32.0 * np.finfo(float).eps]
    dense_theta = dense_theta[increasing]
    dense_phi = dense_phi[increasing]
    if len(dense_theta) < 2 or dense_theta[-1] - dense_theta[0] < pi - 1e-7:
        raise RuntimeError(
            "The analytic 1D1A envelope is not monotone on the left half-plane."
        )
    desired_theta = np.linspace(0.5 * pi, 1.5 * pi, n_half + 1)
    phi = np.interp(desired_theta, dense_theta, dense_phi)
    left = envelope(phi)
    left[0, 0] = 0.0
    left[-1, 0] = 0.0
    right = left[-2::-1].copy()
    right[:, 0] *= -1.0
    barrier = np.vstack((left, right, left[:1]))
    barrier[np.abs(barrier) < 1e-15] = 0.0
    return barrier


def one_defender_barrier(
    D: Any,
    radius: float = 1.0,
    alpha: float = 2.0 / 3.0,
    resolution: int = 2000,
) -> np.ndarray:
    """Compute the complete ordered 1D1A barrier for any defender direction."""

    defender = _as_point(D, "D")
    if radius <= 0.0:
        raise ValueError("radius must be positive.")
    if not 0.0 < alpha <= 1.0:
        raise ValueError("alpha must satisfy 0 < alpha <= 1.")
    if int(resolution) < 160:
        raise ValueError("resolution must be at least 160.")
    defender_radius = float(np.linalg.norm(defender))
    if defender_radius < radius - 1e-12:
        raise ValueError("A defender cannot lie inside the target disk.")
    angle = atan2(defender[1], defender[0])
    to_canonical = _rotation(0.5 * pi - angle)
    canonical = _canonical_one_defender_barrier(
        defender_radius, radius, alpha, int(resolution)
    )
    return canonical @ to_canonical


def one_defender_tangent_point(
    D: Any,
    p: Any,
    sigma: int,
    radius: float = 1.0,
    alpha: float = 2.0 / 3.0,
    distance: float | None = None,
) -> np.ndarray:
    """Return the analytic 1D1A-barrier tangency generated by target point p."""

    defender, target = _as_point(D, "D"), _as_point(p, "p")
    if radius <= 0.0:
        raise ValueError("radius must be positive.")
    if not 0.0 < alpha <= 1.0:
        raise ValueError("alpha must satisfy 0 < alpha <= 1.")
    if sigma not in (-1, +1):
        raise ValueError("sigma must be +1 or -1.")
    if abs(np.linalg.norm(target) - radius) > 1e-8 * max(1.0, radius):
        raise ValueError("p must lie on the target boundary.")

    target_angle = atan2(target[1], target[0]) % TAU
    geometry = solve_p_module.geometry(defender, radius)
    directional_distance = float(
        solve_p_module.dsp(geometry, target_angle, sigma, radius)
    )
    if directional_distance <= 1e-14:
        raise ValueError("Tangency is degenerate when defender and p coincide.")
    tangent = np.array([-sin(target_angle), cos(target_angle)])
    derivative = boundary_derivative(geometry, target_angle, sigma, radius)

    common_distance = directional_distance if distance is None else float(distance)
    distance_tolerance = 1e-7 * max(1.0, directional_distance, abs(common_distance))
    if not np.isfinite(common_distance) or common_distance < 0.0:
        raise ValueError("distance must be finite and nonnegative.")
    if abs(common_distance - directional_distance) > distance_tolerance:
        raise ValueError(
            "The supplied distance does not agree with the defender DSP at p."
        )

    tangential = float(np.clip(-alpha * derivative / radius, -1.0, 1.0))
    radial = sqrt(max(0.0, 1.0 - tangential * tangential))
    outward_direction = radial * target / radius + tangential * tangent
    return target + alpha * common_distance * outward_direction


def _canonical_transform(
    D1: np.ndarray, D2: np.ndarray
) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    """Order, rotate, and optionally reflect a defender pair."""

    defenders = np.vstack((D1, D2))
    swapped = bool(np.linalg.norm(defenders[0]) > np.linalg.norm(defenders[1]) + 1e-12)
    if swapped:
        defenders = defenders[::-1].copy()
    theta1 = atan2(defenders[0, 1], defenders[0, 0])
    transform = _rotation(0.5 * pi - theta1)
    canonical = defenders @ transform.T
    reflected = bool(canonical[1, 0] > 1e-12)
    if reflected:
        reflection = np.diag([-1.0, 1.0])
        transform = reflection @ transform
        canonical = defenders @ transform.T
    canonical[np.abs(canonical) < 1e-14] = 0.0
    return (
        defenders,
        canonical,
        {
            "swapped": swapped,
            "reflected": reflected,
            "transform": transform,
        },
    )


class _ActivityEvaluator:
    """Sample all requested value branches on the complete target boundary."""

    def __init__(
        self,
        defenders: np.ndarray,
        radius: float,
        alpha: float,
        resolution: int,
        exact_angles: list[float],
        sample_count: int | None = None,
        defender_alphas: tuple[float, float] | None = None,
        modes: tuple[tuple[int, int], ...] | None = None,
    ) -> None:
        count = (
            max(180, int(sample_count))
            if sample_count is not None
            else max(1440, min(5000, int(resolution)))
        )
        angles = list(np.linspace(0.0, TAU, count, endpoint=False)) + list(exact_angles)
        self.angles = np.asarray(angles)
        self.radius = radius
        geometries = [
            solve_p_module.geometry(defender, radius) for defender in defenders
        ]
        ratios = np.asarray(
            (alpha, alpha) if defender_alphas is None else defender_alphas,
            dtype=float,
        )
        if ratios.shape != (2,) or np.any(ratios <= 0.0) or np.any(ratios > 1.0):
            raise ValueError("defender_alphas must contain two ratios in (0, 1].")
        enabled_modes = solve_p_module.MODES if modes is None else tuple(modes)
        self.capacities = []
        for mode in enabled_modes:
            d1 = solve_p_module.dsp(geometries[0], self.angles, mode[0], radius)
            d2 = solve_p_module.dsp(geometries[1], self.angles, mode[1], radius)
            self.capacities.append(np.minimum(ratios[0] * d1, ratios[1] * d2))

    def margin(self, attackers: np.ndarray) -> np.ndarray:
        states = np.atleast_2d(np.asarray(attackers, dtype=float))
        answer = np.full(len(states), -np.inf)
        for first in range(0, len(states), 32):
            chunk = states[first : first + 32]
            attacker_angles = np.arctan2(chunk[:, 1], chunk[:, 0])[:, None]
            delta = (self.angles[None, :] - attacker_angles + pi) % TAU - pi
            distances = lifted_distance(
                (np.linalg.norm(chunk, axis=1)[:, None], 0.0),
                self.radius,
                delta,
                self.radius,
            )
            values = np.maximum.reduce(
                [
                    np.max(capacity[None, :] - distances, axis=1)
                    for capacity in self.capacities
                ]
            )
            answer[first : first + len(chunk)] = values
        return answer


def _mapped_mode(
    mode: tuple[str, str], swapped: bool, reflected: bool
) -> tuple[str, str]:
    signs = list(mode)
    if reflected:
        signs = ["-" if sign == "+" else "+" if sign == "-" else sign for sign in signs]
    if swapped:
        signs.reverse()
    return tuple(signs)


def _circle_arc(
    center: np.ndarray,
    circle_radius: float,
    start: np.ndarray,
    end: np.ndarray,
    ccw: bool,
    resolution: int,
) -> np.ndarray:
    angle0 = atan2((start - center)[1], (start - center)[0])
    angle1 = atan2((end - center)[1], (end - center)[0])
    delta = (angle1 - angle0) % TAU if ccw else -((angle0 - angle1) % TAU)
    count = max(16, int(ceil(abs(delta) / TAU * max(160, resolution))))
    angles = angle0 + np.linspace(0.0, delta, count + 1)
    points = center + circle_radius * np.column_stack((np.cos(angles), np.sin(angles)))
    points[0], points[-1] = start, end
    return points


def _select_active_arc(
    center: np.ndarray,
    circle_radius: float,
    tangent1: np.ndarray,
    tangent2: np.ndarray,
    evaluator: _ActivityEvaluator,
    target_radius: float,
    resolution: int,
) -> tuple[np.ndarray, float]:
    """Select the tangent-to-tangent arc using the full value activity test."""

    if np.linalg.norm(tangent1 - tangent2) <= 1e-10 * max(1.0, circle_radius):
        return np.empty((0, 2), dtype=float), 0.0

    options = [
        _circle_arc(center, circle_radius, tangent1, tangent2, True, resolution),
        _circle_arc(center, circle_radius, tangent1, tangent2, False, resolution),
    ]
    scores = []
    for arc in options:
        indices = np.linspace(0, len(arc) - 1, min(25, len(arc))).round().astype(int)
        sample = arc[np.unique(indices)]
        margin = evaluator.margin(sample)
        covered = np.maximum(margin, 0.0)
        disk_depth = np.maximum(target_radius - np.linalg.norm(sample, axis=1), 0.0)
        length = float(np.sum(np.linalg.norm(np.diff(arc, axis=0), axis=1)))
        scores.append(
            float(
                1000.0 * np.max(disk_depth)
                + 8.0 * np.max(covered)
                + np.mean(covered)
                + 1e-9 * length
            )
        )
    selected = int(np.argmin(scores))
    return options[selected], scores[selected]


def _polyline_segments(
    curves: list[np.ndarray],
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Flatten finite, nonzero polyline segments for radial intersection tests."""

    starts_list: list[np.ndarray] = []
    vectors_list: list[np.ndarray] = []
    sources_list: list[np.ndarray] = []
    for source_index, curve in enumerate(curves):
        points = np.asarray(curve, dtype=float)
        if points.ndim != 2 or points.shape[1] != 2 or len(points) < 2:
            continue
        if not np.all(np.isfinite(points)):
            raise ValueError("Envelope source curves must contain finite points.")
        vectors = np.diff(points, axis=0)
        nonzero = np.linalg.norm(vectors, axis=1) > 1e-14
        starts_list.append(points[:-1][nonzero])
        vectors_list.append(vectors[nonzero])
        sources_list.append(
            np.full(int(np.count_nonzero(nonzero)), source_index, dtype=int)
        )
    if not starts_list or not any(len(values) for values in starts_list):
        return (
            np.empty((0, 2), dtype=float),
            np.empty((0, 2), dtype=float),
            np.empty(0, dtype=int),
        )
    return np.vstack(starts_list), np.vstack(vectors_list), np.concatenate(sources_list)


def _ray_segment_radii(
    starts: np.ndarray,
    vectors: np.ndarray,
    direction: np.ndarray,
    target_radius: float,
) -> np.ndarray:
    """Return ray radii for every valid segment hit and inf otherwise."""

    if len(starts) == 0:
        return np.empty(0, dtype=float)
    scale = max(1.0, target_radius, float(np.max(np.linalg.norm(starts, axis=1))))
    denominators = vectors[:, 0] * direction[1] - vectors[:, 1] * direction[0]
    numerators = -(starts[:, 0] * direction[1] - starts[:, 1] * direction[0])
    usable = np.abs(denominators) > 2e-14 * scale
    parameters = np.zeros_like(denominators)
    parameters[usable] = numerators[usable] / denominators[usable]
    hits = starts + parameters[:, None] * vectors
    radial = hits @ direction
    valid = (
        usable
        & (parameters >= -1e-10)
        & (parameters <= 1.0 + 1e-10)
        & (radial >= target_radius - 2e-9 * max(1.0, target_radius))
    )
    return np.where(valid, radial, np.inf)


def _nearest_ray_radius(
    starts: np.ndarray,
    vectors: np.ndarray,
    direction: np.ndarray,
    target_radius: float,
) -> float:
    """Return the first exterior intersection of a ray with source segments."""

    radii = _ray_segment_radii(starts, vectors, direction, target_radius)
    return float(np.min(radii)) if len(radii) else float("inf")


def _source_transition_point(
    source_segments: list[tuple[np.ndarray, np.ndarray]],
    source1: int,
    source2: int,
    angle1: float,
    angle2: float,
    target_radius: float,
) -> np.ndarray:
    """Locate a source switch by radial-distance equality on the two curves."""

    def radii(angle: float) -> tuple[float, float]:
        direction = np.array([np.cos(angle), np.sin(angle)])
        first = _nearest_ray_radius(*source_segments[source1], direction, target_radius)
        second = _nearest_ray_radius(
            *source_segments[source2], direction, target_radius
        )
        return first, second

    sample_angles = np.linspace(angle1, angle2, 17)
    samples = []
    for angle in sample_angles:
        first, second = radii(float(angle))
        if np.isfinite(first) and np.isfinite(second):
            samples.append((float(angle), first - second, first, second))
    if not samples:
        raise RuntimeError("Envelope source curves have no common radial interval.")

    bracket = None
    for left, right in zip(samples[:-1], samples[1:]):
        if left[1] == 0.0 or left[1] * right[1] <= 0.0:
            bracket = (left[0], right[0])
            break
    if bracket is not None:
        lo, hi = bracket
        flo = radii(lo)[0] - radii(lo)[1]
        for _ in range(55):
            mid = 0.5 * (lo + hi)
            first, second = radii(mid)
            fmid = first - second
            if not np.isfinite(fmid):
                break
            if abs(fmid) <= 2e-12 * max(1.0, first, second):
                lo = hi = mid
                break
            if flo * fmid <= 0.0:
                hi = mid
            else:
                lo, flo = mid, fmid
        angle = 0.5 * (lo + hi)
        first, second = radii(angle)
    else:
        # Tangential or sub-resolution switches may not change sign.  Use the
        # sampled point with the smallest radial mismatch.
        angle, _, first, second = min(samples, key=lambda item: abs(item[1]))
    radius = 0.5 * (first + second)
    return radius * np.array([np.cos(angle), np.sin(angle)])


def _split_envelope_runs(
    envelope: np.ndarray,
    source_indices: np.ndarray,
    transitions: dict[int, np.ndarray],
    source_names: list[str],
) -> list[dict[str, Any]]:
    """Split a cyclic sampled envelope into ordered, source-labelled runs."""

    count = len(envelope)
    changes = sorted(transitions)
    if not changes:
        points = np.vstack((envelope, envelope[:1]))
        return [
            {
                "source_index": int(source_indices[0]),
                "source": source_names[int(source_indices[0])],
                "points": points,
                "start_point": points[0],
                "end_point": points[-1],
            }
        ]

    runs = []
    for change_position, previous_change in enumerate(changes):
        next_change = changes[(change_position + 1) % len(changes)]
        start_index = (previous_change + 1) % count
        indices = [start_index]
        while indices[-1] != next_change:
            indices.append((indices[-1] + 1) % count)
        source_index = int(source_indices[start_index])
        points = np.vstack(
            (
                transitions[previous_change],
                envelope[np.asarray(indices, dtype=int)],
                transitions[next_change],
            )
        )
        runs.append(
            {
                "source_index": source_index,
                "source": source_names[source_index],
                "points": points,
                "start_point": points[0],
                "end_point": points[-1],
            }
        )
    return runs


def _circle_circle_points(
    center1: np.ndarray,
    radius1: float,
    center2: np.ndarray,
    radius2: float,
) -> list[np.ndarray]:
    """Return isolated intersections of two cooperative candidate circles."""

    delta = center2 - center1
    distance = float(np.linalg.norm(delta))
    scale = max(1.0, distance, radius1, radius2)
    tolerance = 2e-11 * scale
    if (
        distance <= tolerance
        or distance > radius1 + radius2 + tolerance
        or distance < abs(radius1 - radius2) - tolerance
    ):
        return []
    along = (radius1 * radius1 - radius2 * radius2 + distance * distance) / (
        2.0 * distance
    )
    height2 = radius1 * radius1 - along * along
    if height2 < -tolerance * scale:
        return []
    base = center1 + along * delta / distance
    if height2 <= tolerance * scale:
        return [base]
    normal = np.array([-delta[1], delta[0]]) / distance
    offset = np.sqrt(max(0.0, height2)) * normal
    return [base + offset, base - offset]


def _sampling_position_tolerance(
    point: np.ndarray,
    target_radius: float,
    resolution: int,
) -> float:
    """Return a scale- and sampling-aware positional tolerance."""

    scale = max(1.0, target_radius, float(np.linalg.norm(point)))
    spacing_factor = (300.0 / max(300, int(resolution))) ** 2
    return (1e-7 + 8e-5 * spacing_factor) * scale


def _refine_envelope_intersections(
    segments: list[dict[str, Any]],
    intersections: list[dict[str, Any]],
    p_items: list[dict[str, Any]],
    target_radius: float,
    resolution: int,
) -> np.ndarray:
    """Snap sampled switches to available analytic intersections/tangencies."""

    p_by_label = {item["label"]: item for item in p_items}
    tangent_records = [
        {
            "point": np.asarray(point, dtype=float),
            "p_source": item["label"],
            "defender_source": source,
        }
        for item in p_items
        for source, point in item["tangent_points"].items()
    ]
    angular_tolerance = 1.6 * TAU / max(360, int(resolution))
    for intersection in intersections:
        source1, source2 = intersection["sources"]
        approximate = intersection["point"]
        candidates: list[np.ndarray] = []
        defender_source = next(
            (source for source in (source1, source2) if source in {"D1", "D2"}),
            None,
        )
        p_source = next(
            (source for source in (source1, source2) if source in p_by_label),
            None,
        )
        if defender_source is not None and p_source is not None:
            candidates = [p_by_label[p_source]["tangent_points"][defender_source]]
        elif source1 in p_by_label and source2 in p_by_label:
            first, second = p_by_label[source1], p_by_label[source2]
            candidates = _circle_circle_points(
                first["point"],
                first["circle_radius"],
                second["point"],
                second["circle_radius"],
            )
        if candidates:
            approximate_angle = atan2(approximate[1], approximate[0])
            candidate = min(
                candidates,
                key=lambda point: abs(
                    (atan2(point[1], point[0]) - approximate_angle + pi) % TAU - pi
                ),
            )
            angle_error = abs(
                (atan2(candidate[1], candidate[0]) - approximate_angle + pi) % TAU - pi
            )
            if angle_error <= angular_tolerance:
                intersection["point"] = np.asarray(candidate, dtype=float).copy()

        # Equal- or nearly equal-speed configurations can make a theoretical
        # multi-curve tangency appear as several slightly separated numerical
        # intersections.  Snap the refined point to the nearest exact p-to-D
        # tangency using the same sampling-aware tolerance as the envelope
        # membership test below.
        point = intersection["point"]
        relevant_tangencies = [
            record
            for record in tangent_records
            if record["p_source"] in intersection["sources"]
        ]
        if relevant_tangencies:
            distances = np.asarray(
                [
                    np.linalg.norm(point - record["point"])
                    for record in relevant_tangencies
                ]
            )
            nearest_index = int(np.argmin(distances))
            nearest = relevant_tangencies[nearest_index]
            nearest_distance = float(distances[nearest_index])
            tolerance = _sampling_position_tolerance(point, target_radius, resolution)
            coincides = nearest_distance <= tolerance
            if coincides:
                intersection["point"] = nearest["point"].copy()
                intersection["tangency_p_source"] = nearest["p_source"]
                intersection["tangency_defender_source"] = nearest["defender_source"]
        else:
            nearest_distance = float("inf")
            tolerance = _sampling_position_tolerance(point, target_radius, resolution)
            coincides = False
        intersection["tangency_distance"] = nearest_distance
        intersection["tangency_tolerance"] = tolerance
        intersection["coincides_with_tangency"] = bool(coincides)

    if intersections:
        for index, segment in enumerate(segments):
            start = intersections[index]["point"]
            end = intersections[(index + 1) % len(intersections)]["point"]
            segment["points"][0] = start
            segment["points"][-1] = end
            segment["start_point"] = start
            segment["end_point"] = end
    joined = [segments[0]["points"]]
    joined.extend(segment["points"][1:] for segment in segments[1:])
    closed = np.vstack(joined)
    if np.linalg.norm(closed[-1] - closed[0]) > 1e-12:
        closed = np.vstack((closed, closed[:1]))
    else:
        closed[-1] = closed[0]
    return closed


def _endpoint_unit_tangent(
    points: np.ndarray,
    at_start: bool,
    scale: float,
) -> np.ndarray | None:
    """Estimate an oriented one-sided tangent from a sampled envelope run."""

    points = np.asarray(points, dtype=float)
    if len(points) < 2:
        return None
    endpoint = points[0] if at_start else points[-1]
    endpoint_angle = atan2(endpoint[1], endpoint[0]) % TAU
    candidates = points[1:] if at_start else points[-2::-1]
    for candidate in candidates:
        candidate_angle = atan2(candidate[1], candidate[0]) % TAU
        angular_advance = (
            (candidate_angle - endpoint_angle) % TAU
            if at_start
            else (endpoint_angle - candidate_angle) % TAU
        )
        # Analytic snapping can move a transition slightly beyond the nearest
        # angular grid point.  Ignore that one-point numerical backtrack and
        # estimate the tangent from the first point in the actual traversal
        # direction of the radial envelope.
        if angular_advance > pi:
            continue
        vector = candidate - endpoint if at_start else endpoint - candidate
        length = float(np.linalg.norm(vector))
        if length > 1e-12 * scale:
            return vector / length
    return None


def _transition_tangent_angle(
    segments: list[dict[str, Any]],
    intersection_index: int,
    target_radius: float,
    p_items: list[dict[str, Any]],
) -> float:
    """Return the angle between incoming and outgoing envelope tangents."""

    point = np.asarray(segments[intersection_index]["start_point"], dtype=float)
    scale = max(1.0, target_radius, float(np.linalg.norm(point)))
    p_by_label = {item["label"]: item for item in p_items}

    def source_tangent(segment: dict[str, Any], at_start: bool) -> np.ndarray | None:
        item = p_by_label.get(segment["source"])
        if item is not None:
            normal = point - item["point"]
            length = float(np.linalg.norm(normal))
            if length > 1e-12 * scale:
                tangent = np.array([-normal[1], normal[0]]) / length
                angular_direction = point[0] * tangent[1] - point[1] * tangent[0]
                if angular_direction < 0.0:
                    tangent = -tangent
                if abs(angular_direction) > 1e-12 * scale:
                    return tangent
        return _endpoint_unit_tangent(segment["points"], at_start=at_start, scale=scale)

    incoming = source_tangent(
        segments[(intersection_index - 1) % len(segments)],
        at_start=False,
    )
    outgoing = source_tangent(
        segments[intersection_index],
        at_start=True,
    )
    if incoming is None or outgoing is None:
        return float("inf")
    cross = incoming[0] * outgoing[1] - incoming[1] * outgoing[0]
    dot = float(np.clip(incoming @ outgoing, -1.0, 1.0))
    return float(np.arctan2(abs(cross), dot))


def _closest_radial_envelope(
    curves: list[np.ndarray],
    source_names: list[str],
    target_radius: float,
    resolution: int,
) -> tuple[np.ndarray, list[dict[str, Any]], list[dict[str, Any]]]:
    """Return the closest-to-target closed envelope of displayed polylines.

    Every output point is an intersection of a target-centred ray with one of
    the supplied 1D1A barriers or p arcs.  Selecting the smallest exterior
    radius at each angle directly promotes the visible portions of those
    diagnostic curves directly, without calling a separate complete-barrier
    case constructor.
    """

    if len(curves) != len(source_names):
        raise ValueError("Every envelope curve must have one source name.")
    starts, vectors, segment_sources = _polyline_segments(curves)
    if len(starts) == 0:
        return np.empty((0, 2), dtype=float), [], []

    count = max(360, int(resolution))
    angles = np.linspace(0.0, TAU, count, endpoint=False)
    directions = np.column_stack((np.cos(angles), np.sin(angles)))
    radii = np.full(count, np.inf, dtype=float)
    source_indices = np.full(count, -1, dtype=int)

    # Vectorize over all source segments for each ray.  With the viewer's
    # resolutions this uses little memory and is faster than building spatial
    # indices that would need to be rebuilt after every mouse movement.
    for index, direction in enumerate(directions):
        hits = _ray_segment_radii(starts, vectors, direction, target_radius)
        if len(hits):
            segment_index = int(np.argmin(hits))
            radii[index] = hits[segment_index]
            source_indices[index] = segment_sources[segment_index]

    missing = ~np.isfinite(radii)
    if np.any(missing):
        raise RuntimeError(
            f"Closest-curve envelope has {int(np.count_nonzero(missing))} angular gaps."
        )
    envelope = radii[:, None] * directions
    source_segments = []
    for curve in curves:
        curve_starts, curve_vectors, _ = _polyline_segments([curve])
        source_segments.append((curve_starts, curve_vectors))
    angle_step = TAU / count
    change_edges = [
        index
        for index in range(count)
        if source_indices[index] != source_indices[(index + 1) % count]
    ]
    transition_map = {}
    intersections = []
    for edge_index in change_edges:
        source1 = int(source_indices[edge_index])
        source2 = int(source_indices[(edge_index + 1) % count])
        point = _source_transition_point(
            source_segments,
            source1,
            source2,
            edge_index * angle_step,
            (edge_index + 1) * angle_step,
            target_radius,
        )
        transition_map[edge_index] = point
        intersections.append(
            {
                "point": point,
                "sources": (source_names[source1], source_names[source2]),
                "source_indices": (source1, source2),
            }
        )
    runs = _split_envelope_runs(envelope, source_indices, transition_map, source_names)
    joined = [runs[0]["points"]]
    joined.extend(run["points"][1:] for run in runs[1:])
    closed = np.vstack(joined)
    if np.linalg.norm(closed[-1] - closed[0]) > 1e-12:
        closed = np.vstack((closed, closed[:1]))
    else:
        closed[-1] = closed[0]
    return closed, runs, intersections


def compute_geometry_scene(
    D1: Any,
    D2: Any,
    radius: float,
    alpha: float,
    resolution: int,
    beta: float = 1.0,
) -> dict[str, Any]:
    """Return GUI-independent unequal-speed p and barrier geometry.

    The public ratios are ``alpha=v_A/v_D2`` and ``beta=v_D2/v_D1``.
    Consequently the individual attacker/defender ratios are
    ``alpha*beta`` for displayed D1 and ``alpha`` for displayed D2.
    """

    start_time = time.perf_counter()
    displayed = np.asarray([D1, D2], dtype=float)
    if displayed.shape != (2, 2) or not np.all(np.isfinite(displayed)):
        raise ValueError("D1 and D2 must be finite two-dimensional points.")
    if radius <= 0.0:
        raise ValueError("radius must be positive.")
    alpha, beta = float(alpha), float(beta)
    if not 0.0 < alpha < 1.0:
        raise ValueError("alpha=v_A/v_D2 must satisfy 0 < alpha < 1.")
    if not beta > 0.0 or alpha * beta > 1.0:
        raise ValueError("require beta=v_D2/v_D1>0 and v_A/v_D1=alpha*beta<=1")
    if int(resolution) < 160:
        raise ValueError("resolution must be at least 160.")
    if np.any(np.linalg.norm(displayed, axis=1) <= radius):
        raise ValueError("Defenders must lie strictly outside the target disk.")

    _, canonical, transform_data = _canonical_transform(displayed[0], displayed[1])
    swapped = bool(transform_data["swapped"])
    reflected = bool(transform_data["reflected"])
    display_alphas = (alpha * beta, alpha)
    # solve_p normalizes speed by its first (radially nearer) defender.  If
    # canonicalization swaps displayed labels, the internal speed ratio and
    # attacker ratio must be inverted/remapped with the geometry.
    canonical_beta = 1.0 / beta if swapped else beta
    canonical_alpha = alpha if swapped else alpha * beta
    canonical_first_speed = beta if swapped else 1.0
    preview = int(resolution) <= 300
    p_solution = solve_p_module.solve_p(
        canonical[0],
        canonical[1],
        radius=radius,
        alpha=canonical_alpha,
        beta=canonical_beta,
    )
    canonical_distance_limits = [
        float(p_solution["d1_max"]),
        float(p_solution["d2_max"]),
    ]
    display_distance_limits = (
        canonical_distance_limits[::-1] if swapped else canonical_distance_limits
    )
    feasible_candidates = [
        candidate
        for candidate in p_solution["candidates"]
        if candidate["distance_feasible"]
    ]

    transform = transform_data["transform"]
    prepared = []
    mode_counts: dict[tuple[str, str], int] = {}
    for candidate in feasible_candidates:
        canonical_mode = tuple(candidate["mode"])
        display_mode = _mapped_mode(canonical_mode, swapped, reflected)
        display_effective_mode = _mapped_mode(
            tuple(candidate.get("effective_mode", canonical_mode)),
            swapped,
            reflected,
        )
        display_direct = tuple(candidate.get("direct", (False, False)))
        if swapped:
            display_direct = display_direct[::-1]
        mode_counts[display_mode] = mode_counts.get(display_mode, 0) + 1
        base = MODE_LABELS.get(display_mode, f"p{candidate['mode_index'] + 1}")
        label = (
            base
            if mode_counts[display_mode] == 1
            else f"{base}_{mode_counts[display_mode]}"
        )
        canonical_paths = [float(candidate["d1"]), float(candidate["d2"])]
        display_paths = canonical_paths[::-1] if swapped else canonical_paths
        arrival_time = float(candidate["arrival_time"]) / canonical_first_speed
        prepared.append(
            {
                "label": label,
                "point": np.asarray(candidate["p"] @ transform, dtype=float),
                "mode": display_mode,
                "effective_mode": display_effective_mode,
                "direct": display_direct,
                "d": arrival_time,
                "arrival_time": arrival_time,
                "path_lengths": {"D1": display_paths[0], "D2": display_paths[1]},
                "circle_radius": canonical_alpha * float(candidate["d"]),
                "canonical_phi": float(candidate["phi"]),
                "mode_index": int(candidate["mode_index"]),
            }
        )

    exact_angles = [
        atan2(item["point"][1], item["point"][0]) % TAU for item in prepared
    ]
    evaluator = _ActivityEvaluator(
        displayed,
        radius,
        alpha * beta,
        int(resolution),
        exact_angles,
        sample_count=360 if preview else None,
        defender_alphas=display_alphas,
        modes=solve_p_module.MODES,
    )
    barriers = {
        "D1": one_defender_barrier(
            displayed[0], radius, display_alphas[0], int(resolution)
        ),
        "D2": one_defender_barrier(
            displayed[1], radius, display_alphas[1], int(resolution)
        ),
    }

    p_items = []
    residuals = []
    canonical_geometries = [
        solve_p_module.geometry(canonical[index], radius) for index in range(2)
    ]
    for item, candidate in zip(prepared, feasible_candidates):
        mode = item["mode"]
        tangencies = {}
        for defender_index, source in enumerate(("D1", "D2")):
            sigma = +1 if mode[defender_index] == "+" else -1
            tangencies[source] = one_defender_tangent_point(
                displayed[defender_index],
                item["point"],
                sigma,
                radius=radius,
                alpha=display_alphas[defender_index],
                distance=item["path_lengths"][source],
            )
        circle_radius = item["circle_radius"]
        arc, arc_score = _select_active_arc(
            item["point"],
            circle_radius,
            tangencies["D1"],
            tangencies["D2"],
            evaluator,
            radius,
            int(resolution),
        )
        p_items.append(
            {
                **item,
                "tangent_points": tangencies,
                "arc_points": arc,
                "arc_activity_score": float(arc_score),
            }
        )

        canonical_mode = solve_p_module.MODES[candidate["mode_index"]]
        arrival1 = solve_p_module.dsp(
            canonical_geometries[0], candidate["phi"], canonical_mode[0], radius
        )
        arrival2 = solve_p_module.dsp(
            canonical_geometries[1], candidate["phi"], canonical_mode[1], radius
        )
        residuals.extend(
            [
                abs(float(np.linalg.norm(item["point"]) - radius)),
                abs(float(arrival1 - arrival2 / canonical_beta)),
                abs(
                    float(
                        np.linalg.norm(tangencies["D1"] - item["point"]) - circle_radius
                    )
                ),
                abs(
                    float(
                        np.linalg.norm(tangencies["D2"] - item["point"]) - circle_radius
                    )
                ),
            ]
        )

    envelope_curves = [
        barriers["D1"],
        barriers["D2"],
        *(item["arc_points"] for item in p_items),
    ]
    envelope_sources = ["D1", "D2", *(item["label"] for item in p_items)]
    closed_barrier, envelope_segments, envelope_intersections = (
        _closest_radial_envelope(
            envelope_curves,
            envelope_sources,
            radius,
            int(resolution),
        )
    )
    closed_barrier = _refine_envelope_intersections(
        envelope_segments,
        envelope_intersections,
        p_items,
        radius,
        int(resolution),
    )
    envelope_starts, envelope_vectors, _ = _polyline_segments(envelope_curves)
    for item in p_items:
        item["tangent_on_envelope"] = {}
        for source, point in item["tangent_points"].items():
            point_radius = float(np.linalg.norm(point))
            direction = point / point_radius
            nearest_radius = _nearest_ray_radius(
                envelope_starts, envelope_vectors, direction, radius
            )
            # The analytic tangency is tested against sampled source
            # polylines using their resolution-scaled chord-error tolerance.
            tolerance = _sampling_position_tolerance(point, radius, int(resolution))
            item["tangent_on_envelope"][source] = bool(
                np.isfinite(nearest_radius)
                and abs(point_radius - nearest_radius) <= tolerance
            )
    visible_envelope_intersections = []
    tangent_angle_tolerance = 4.0 * TAU / max(360, int(resolution)) + 1e-6
    for index, intersection in enumerate(envelope_intersections):
        tangent_angle = _transition_tangent_angle(
            envelope_segments,
            index,
            radius,
            p_items,
        )
        tangent_continuous = bool(
            np.isfinite(tangent_angle) and tangent_angle <= tangent_angle_tolerance
        )
        intersection["tangent_angle"] = tangent_angle
        intersection["tangent_angle_tolerance"] = tangent_angle_tolerance
        intersection["sampled_tangent_continuous"] = tangent_continuous
        intersection["tangent_continuous"] = bool(
            intersection["coincides_with_tangency"] or tangent_continuous
        )
        intersection["is_singular"] = not intersection["tangent_continuous"]
        if intersection["is_singular"]:
            visible_envelope_intersections.append(intersection)
    finite = all(
        np.all(np.isfinite(points))
        for points in [
            *barriers.values(),
            *(item["arc_points"] for item in p_items),
            *(segment["points"] for segment in envelope_segments),
            *(intersection["point"] for intersection in envelope_intersections),
            closed_barrier,
        ]
    )
    residuals.append(0.0 if finite else float("inf"))
    return {
        "p_status": p_solution["status"],
        "enabled_modes": tuple(p_solution["modes"]),
        "root_intervals": tuple(p_solution["root_intervals"]),
        "distance_limits": {
            "D1": display_distance_limits[0],
            "D2": display_distance_limits[1],
        },
        "defenders": displayed.copy(),
        "barriers": barriers,
        "closed_barrier": closed_barrier,
        "envelope_segments": envelope_segments,
        "envelope_intersections": envelope_intersections,
        "visible_envelope_intersections": visible_envelope_intersections,
        "envelope_sources": tuple(envelope_sources),
        "p_items": p_items,
        "residual": float(max(residuals, default=0.0)),
        "computation_time": time.perf_counter() - start_time,
        "resolution": int(resolution),
        "alpha": alpha,
        "beta": beta,
        "defender_alphas": {"D1": display_alphas[0], "D2": display_alphas[1]},
        "canonical_mapping": {
            "swapped": swapped,
            "reflected": reflected,
            "relabeling_active": swapped,
            "canonical_alpha": canonical_alpha,
            "canonical_beta": canonical_beta,
        },
    }
